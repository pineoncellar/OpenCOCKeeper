# ====================================================================
# 文件加载与缓存
# ====================================================================

def _load_prompts_yaml() -> Dict[str, Any]:
    """读取 prompts.yaml，解析失败或缺失时返回空 dict（走内置默认值兜底）。"""
    if not PROMPTS_FILE.exists():
        _warn(f"未找到 {PROMPTS_FILE}，将使用内置默认提示词")
        return {}
    try:
        with open(PROMPTS_FILE, "r", encoding="utf-8") as f:
            return yaml.safe_load(f) or {}
    except Exception as e:  # noqa: BLE001
        _warn(f"无法读取 prompts.yaml: {e}，将使用内置默认提示词")
        return {}


def _get_file_value(key: str, data: Dict[str, Any]) -> Optional[str]:
    """按点号路径从文件数据中取值；路径中断或值非 str 返回 None。"""
    node: Any = data
    for part in key.split("."):
        if isinstance(node, dict) and part in node:
            node = node[part]
        else:
            return None
    return node if isinstance(node, str) else None


# ── 全局单例（懒加载缓存整份文件，避免逐 key 读盘） ──
_cache: Optional[Dict[str, Any]] = None


def _file_data() -> Dict[str, Any]:
    global _cache
    if _cache is None:
        _cache = _load_prompts_yaml()
    return _cache


