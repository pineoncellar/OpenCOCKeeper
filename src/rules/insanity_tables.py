# ====================================================================
# 掷骰取表辅助（纯函数，支持 rng 注入保证可复现测试）
# ====================================================================


def _table_pick(table: Dict[int, Any], die_sides: int, rng: Optional[object]) -> Any:
    """掷一枚 die_sides 面骰，按骰面查表返回对应条目。

    取最后一个骰子值作为骰面（roll_ndn 返回列表），保证与全库"取末值"惯例一致。
    """
    value = roll_ndn(1, die_sides, rng)[-1]
    return table[value]


def pick_summary_bout(rng: Optional[object] = None) -> Dict[str, Any]:
    """掷 1D10 抽取表 7 疯狂发作·总结症状，返回含 name/narrate 的条目。"""
    return dict(_table_pick(SUMMARY_BOUTS, 10, rng))


def pick_phobia(rng: Optional[object] = None) -> str:
    """掷 1D100 抽取表 9 范例恐惧症，返回恐惧症名。"""
    return _table_pick(PHOBIAS, 100, rng)


def pick_mania(rng: Optional[object] = None) -> str:
    """掷 1D100 抽取表 10 范例躁狂症，返回躁狂症名。"""
    return _table_pick(MANIAS, 100, rng)
